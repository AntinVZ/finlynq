export type StudioTextKey = keyof (typeof STUDIO_TEXT)["uk"];

/** A translator bound to one language (what `useStudioT` returns). */
export type StudioT = (key: StudioTextKey, vars?: Record<string, string | number>) => string;

export function studioT(lang: StudioLang, key: StudioTextKey, vars?: Record<string, string | number>): string {
  const table = STUDIO_TEXT[lang] as Record<string, string>;
  let s = table[key] ?? (STUDIO_TEXT.uk as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
